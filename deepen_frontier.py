# 执行
files = sorted(glob.glob('[0-9]*-*.html'), key=lambda f: int(re.match(r'(\d+)-', f).group(1)))
enhanced = 0
for f in files:
    no = int(re.match(r'(\d+)-', os.path.basename(f)).group(1))
    if no not in DEEPEN: continue
    additions = DEEPEN[no]
    c = open(f).read()
    # 检查是否已添加过（用第一段的唯一标志）
    if additions[0][:30] in c:
        continue
    addition_html = '\n    '.join(additions)
    # 在本章小结前插入
    for marker in ['<h2><span class="idx"></span>本章小结</h2>', '本章小结']:
        if marker in c:
            c = c.replace(marker, addition_html + '\n    ' + marker, 1)
            break
    else:
        if '<div class="chapter-nav">' in c:
            c = c.replace('<div class="chapter-nav">', addition_html + '\n    <div class="chapter-nav">', 1)
    open(f, 'w').write(c)
    enhanced += 1
    print(f'  ch{no}: +{len(additions)}段')

print(f'\n✅ 深化了 {enhanced} 章')
